#!/usr/bin/env node
// Copies shared constants from the ProsERP web app (live-repo, branch main) so the
// mobile app never drifts from the web's permission names, module names or country data.
//
//   node scripts/sync-from-web.mjs [path-to-live-repo]
//
// Reads with `git show main:<path>`, so the web repo's checked-out branch doesn't matter.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const webRepo = resolve(process.argv[2] ?? '../live-repo');
const show = (path) =>
  execFileSync('git', ['-C', webRepo, 'show', `main:${path}`], { encoding: 'utf8' });
const commit = execFileSync('git', ['-C', webRepo, 'rev-parse', '--short', 'main'], {
  encoding: 'utf8',
}).trim();
const header = (source) =>
  `// GENERATED by scripts/sync-from-web.mjs from live-repo main@${commit}:${source}\n// Do not edit by hand — change it on the web side and re-run the script.\n\n`;

const copy = (source, target) => {
  writeFileSync(target, header(source) + show(source));
  console.log(`✓ ${target}`);
};

copy('src/utilities/constants/modules.ts', 'src/constants/modules.ts');
copy('src/utilities/constants/permissions.ts', 'src/constants/permissions.ts');
copy(
  'src/utilities/constants/prosControlPermissions.ts',
  'src/constants/prosControlPermissions.ts'
);
// Excel helpers: mobile builds the same workbooks as web's Next routes, with the same exceljs.
copy('src/lib/excel/styles.ts', 'src/lib/excel/styles.ts');
copy('src/lib/excel/workBook.ts', 'src/lib/excel/workBook.ts');

// countries.ts is ~3,500 lines of TS; keep only what the app uses, as data.
const countriesTs = show('src/utilities/constants/countries.ts');
const arrayLiteral = countriesTs.slice(countriesTs.indexOf('['), countriesTs.lastIndexOf(']') + 1);
const countries = new Function(`return ${arrayLiteral}`)().map((c) => ({
  name: c.name,
  code: c.code,
  dialCode: c.dial_code,
  currency: { code: c.currency.code, name: c.currency.name, symbol: c.currency.symbol },
}));
writeFileSync(
  'src/constants/countries.ts',
  header('src/utilities/constants/countries.ts') +
    `export type Country = { name: string; code: string; dialCode: string; currency: { code: string; name: string; symbol: string } };\n\n` +
    `export const COUNTRIES: Country[] = ${JSON.stringify(countries, null, 1)};\n`
);
console.log(`✓ src/constants/countries.ts (${countries.length} countries)`);
